<?php

declare(strict_types=1);

namespace Xkhm\Service;

use Xkhm\Repository\ClientRepositoryInterface;

/**
 * Password recovery for **clients**.
 *
 * The token lives in the WHMCS columns that already exist —
 * `tblclients.pwresetkey` and `tblclients.pwresetexpiry` — so **the
 * production schema is not touched**.
 *
 * The rules:
 *
 * - the answer is the same whether or not the account exists;
 * - the token expires;
 * - the token is **single-use**: it is cleared when the password is reset;
 * - the new password is stored as bcrypt.
 */
class PasswordResetService
{
    /** How long a reset token is valid: one hour. */
    public const TTL = 3600;

    /**
     * The token generated by the last request — for the diagnostics.
     */
    private ?string $lastToken = null;

    public function __construct(
        private ClientRepositoryInterface $clientRepository,
        private TokenDelivery $delivery,
        private PasswordHasher $hasher
    ) {
    }

    /**
     * Register a reset request.
     *
     * @return bool whether the account exists — the caller must **never**
     *         reveal it
     */
    public function requestReset(string $email): bool
    {
        $email = trim($email);
        if ($email === '') {
            return false;
        }

        $client = $this->clientRepository->findByEmail($email);
        if (!$client) {
            return false;
        }

        $token = bin2hex(random_bytes(32));

        $this->clientRepository->setResetToken(
            (int)$client['id'],
            $token,
            time() + self::TTL
        );

        $this->delivery->deliver($email, $token, 'cliente', $email);
        $this->lastToken = $token;

        return true;
    }

    /**
     * Set a new password with a reset token.
     *
     * @return bool whether the token was valid and the password was changed
     */
    public function resetWithToken(string $token, string $password): bool
    {
        $token = trim($token);
        if ($token === '' || $password === '') {
            return false;
        }

        $client = $this->clientRepository->findByResetToken($token);
        if (!$client) {
            return false;
        }

        $expiry = (int)($client['pwresetexpiry'] ?? 0);
        if ($expiry < time()) {
            // The token is stale: clear it and refuse.
            $this->clientRepository->clearResetToken((int)$client['id']);
            return false;
        }

        $updated = $this->clientRepository->update((int)$client['id'], [
            'password' => $this->hasher->hash($password),
        ]);

        if (!$updated) {
            return false;
        }

        // The token is single-use.
        $this->clientRepository->clearResetToken((int)$client['id']);

        // And it leaves the queue: nobody has to receive a message
        // with a code that no longer works.
        $this->delivery->forget($token, 'cliente');

        return true;
    }

    /**
     * Where the token was delivered — for the diagnostics.
     */
    public function describeDelivery(): string
    {
        return $this->delivery->describe();
    }

    /**
     * The token generated by the last request — for the diagnostics.
     */
    public function lastToken(): ?string
    {
        return $this->lastToken;
    }
}
