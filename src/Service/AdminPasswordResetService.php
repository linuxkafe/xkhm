<?php

declare(strict_types=1);

namespace Xkhm\Service;

use Xkhm\Repository\AdminRepositoryInterface;

/**
 * Password recovery for the **administrator**.
 *
 * `tbladmins` has no `pwresetkey` column, and the production schema must
 * not change. The token therefore lives in a **file** inside the
 * container, with an expiry — zero schema change, and the administrator
 * reads it with `make db-reset-tokens`.
 *
 * The administrator is one known operator account: the recovery is an
 * operational event, not a public feature, and a file-backed store is the
 * honest shape for it.
 */
class AdminPasswordResetService
{
    /** How long a reset token is valid: one hour. */
    public const TTL = 3600;

    /**
     * The token generated by the last request — for the diagnostics.
     */
    private ?string $lastToken = null;

    public function __construct(
        private AdminRepositoryInterface $repository,
        private TokenDelivery $delivery,
        private PasswordHasher $hasher,
        private string $tokenDirectory
    ) {
    }

    /**
     * Register a reset request.
     *
     * @return bool whether the account exists — the caller must **never**
     *         reveal it
     */
    public function requestReset(string $username): bool
    {
        $username = trim($username);
        if ($username === '') {
            return false;
        }

        $admin = $this->repository->findByUsername($username);
        if (!$admin) {
            return false;
        }

        $token = bin2hex(random_bytes(32));

        $this->store($token, [
            'username' => $username,
            'expires' => time() + self::TTL,
        ]);

        // The delivery goes to the administrator's **e-mail address** —
        // the user name is not an address. The account travels with the
        // token so that the message says whose it is.
        $email = trim((string)($admin['email'] ?? ''));
        $recipient = $email !== '' ? $email : $username;

        $this->delivery->deliver($recipient, $token, 'admin', $username);
        $this->lastToken = $token;

        return true;
    }

    /**
     * Set a new password with a reset token.
     */
    public function resetWithToken(string $token, string $password): bool
    {
        $token = trim($token);
        if ($token === '' || $password === '') {
            return false;
        }

        $record = $this->read($token);
        if ($record === null) {
            return false;
        }

        if ((int)($record['expires'] ?? 0) < time()) {
            $this->delete($token);
            return false;
        }

        $username = (string)($record['username'] ?? '');
        $admin = $this->repository->findByUsername($username);
        if (!$admin) {
            return false;
        }

        $hash = $this->hasher->hash($password);

        // Both columns are written: the WHMCS reads one of them and the
        // application tries both.
        $updated = $this->repository->updatePassword((int)$admin['id'], $hash);
        if (!$updated) {
            return false;
        }

        // The token is single-use.
        $this->delete($token);

        return true;
    }

    public function describeDelivery(): string
    {
        return $this->delivery->describe();
    }

    /**
     * The token generated by the last request — for the diagnostics.
     */
    public function lastToken(): ?string
    {
        return $this->lastToken;
    }

    /**
     * @param array<string, mixed> $record
     */
    private function store(string $token, array $record): void
    {
        $directory = rtrim($this->tokenDirectory, '/');

        if (!is_dir($directory) && !@mkdir($directory, 0700, true) && !is_dir($directory)) {
            return;
        }

        $file = sprintf('%s/%s.json', $directory, $token);

        @file_put_contents(
            $file,
            json_encode($record, JSON_UNESCAPED_UNICODE),
            LOCK_EX
        );
        @chmod($file, 0644);
    }

    /**
     * @return array<string, mixed>|null
     */
    private function read(string $token): ?array
    {
        $file = sprintf('%s/%s.json', rtrim($this->tokenDirectory, '/'), $token);

        if (!is_file($file)) {
            return null;
        }

        $raw = @file_get_contents($file);
        if ($raw === false) {
            return null;
        }

        $decoded = json_decode($raw, true);

        return is_array($decoded) ? $decoded : null;
    }

    private function delete(string $token): void
    {
        @unlink(sprintf(
            '%s/%s.json',
            rtrim($this->tokenDirectory, '/'),
            $token
        ));
    }
}
