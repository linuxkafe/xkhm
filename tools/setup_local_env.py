#!/usr/bin/env python3
"""
Prepare the local environment: generate the `.env` with strong passwords.

The `.env` is **not versioned**. It is the one place where the local
credentials live. The repository holds the *shape* of the configuration
(`${XKHM_DB_PASSWORD:?...}`), never the value.

    make db-env            # create the .env
    make db-env REGEN=1    # create a new one (and forget the old)

The passwords it generates are for the **local** database only. The
production credentials are not, and cannot be, in a file in this
repository.
"""

from __future__ import annotations

import os
import pathlib
import stat
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from rotate_db_password import generate_password  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENV_FILE = ROOT / ".env"

TEMPLATE = """\
# Local development environment — NOT versioned.
#
# The credentials live here and nowhere else. The repository holds the
# *shape* of the configuration, never the value.
#
# Generated by `make db-env`.

APP_ENV=development
APP_DEBUG=true
APP_URL=http://localhost:8083

# The local database (the container), published only on the loopback.
# The host already runs a MySQL of its own on 127.0.0.1:3306.
XKHM_DB_HOST=127.0.0.1
XKHM_DB_PORT=13306
XKHM_DB_NAME=linuxkonect
XKHM_DB_USER=linuxkonect
XKHM_DB_PASSWORD={db_password}
XKHM_DB_ROOT_PASSWORD={root_password}

# The WHMCS encryption hash. It is a **shared** secret: the application
# and the WHMCS must agree on it, or the encrypted data in the database
# becomes unreadable. It cannot be generated — it can only be copied.
CC_ENCRYPTION_HASH={encryption_hash}

# The mail: the host's Postfix, on port 25, without authentication.
#
# This is the *host's* configuration: the application runs in a
# container that cannot reach the host, so the host delivers the
# recovery tokens (see `tools/mail_pending_tokens.py`).
XKHM_MAILER_SMTP_HOST=127.0.0.1
XKHM_MAILER_SMTP_PORT=25
XKHM_MAILER_SMTP_FROM={mail_from}
"""


def main() -> int:
    mail_from = os.getenv("XKHM_MAILER_SMTP_FROM", "safedata@linuxkafe.com")

    # The encryption hash cannot be invented: it has to be the same one
    # the WHMCS uses. It comes from the environment, or from the `.env`
    # that is being replaced.
    encryption_hash = os.getenv("CC_ENCRYPTION_HASH", "")

    if not encryption_hash and ENV_FILE.exists():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            if line.startswith("CC_ENCRYPTION_HASH="):
                encryption_hash = line.split("=", 1)[1].strip()
                break

    if not encryption_hash:
        print()
        print("  [ERRO] falta o CC_ENCRYPTION_HASH.")
        print()
        print("  É o segredo **partilhado** com o WHMCS: tem de ser o mesmo")
        print("  valor, ou os dados encriptados na base tornam-se ilegíveis.")
        print("  Indique-o no ambiente:")
        print()
        print("    CC_ENCRYPTION_HASH=... make db-env")
        print()
        return 1

    print()
    print("Preparar o ambiente local")
    print("=" * 62)

    if ENV_FILE.exists() and not os.getenv("REGEN"):
        print(f"  O {ENV_FILE} já existe.")
        print("  Para o refazer: make db-env REGEN=1")
        print()
        return 0

    db_password = generate_password(32)
    root_password = generate_password(32)

    ENV_FILE.write_text(
        TEMPLATE.format(
            db_password=db_password,
            root_password=root_password,
            encryption_hash=encryption_hash,
            mail_from=mail_from,
        ),
        encoding="utf-8",
    )

    # The file holds passwords: only its owner may read it.
    ENV_FILE.chmod(stat.S_IRUSR | stat.S_IWUSR)

    print(f"  [OK]    {ENV_FILE} criado (modo 0600)")
    print(f"          base de dados: {ENV_FILE.parent}")
    print()
    print("  As senhas **locais**. As de produção não vivem aqui.")
    print()

    return 0


if __name__ == "__main__":
    sys.exit(main())
